export function hasStatusPicture(id: string): boolean {
  return id in PICTURES;
}

/** Draws the picture for `id` centred in a box at (x, y) of `size` px; returns false if there is none. */
export function drawStatusPicture(g: CanvasRenderingContext2D, id: string, x: number, y: number, size: number, background = '#ffffff'): boolean {
  const rows = PICTURES[id.startsWith('buff:') ? 'buff' : id] ?? (id === 'buff' ? PICTURES.buff : undefined);
  if (!rows) return false;
  // Dark ink on light tiles, light ink on dark ones (curse, fear and corruption are dark purples).
  const n = parseInt(background.slice(1), 16);
  const luma = (0.299 * ((n >> 16) & 255) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255)) / 255;
  const ink = luma < 0.42 ? '#f4f0e8' : '#120c18';
  const scale = Math.max(1, Math.floor(size / 8));
  const ox = x + Math.round((size - 8 * scale) / 2);
  const oy = y + Math.round((size - 8 * scale) / 2);
  rows.forEach((row, ry) =>
    [...row].forEach((ch, rx) => {
      if (ch === '.') return;
      g.fillStyle = ch === 'o' ? (ink === '#120c18' ? 'rgba(255,255,255,0.65)' : 'rgba(0,0,0,0.5)') : ink;
      g.fillRect(ox + rx * scale, oy + ry * scale, scale, scale);
    }),
  );
  return true;
}
