/**
 * Writes docs/LOCK_STRINGS.md: every player-facing lock and guide string in one place, for review.
 * Run: npx tsx scripts/lockStrings.ts  (rerun after editing locks or systems)
 */
import { writeFileSync } from 'node:fs';
import { content } from '../src/data';
import { leafText } from '../src/engine/locks/locks';
import type { Cond } from '../src/engine/quests/types';

const leaves = (c: Cond, out: Cond[] = []): Cond[] => {
  if (c.kind === 'all' || c.kind === 'any') c.conds.forEach((x) => leaves(x, out));
  else if (c.kind === 'not') leaves(c.cond, out);
  else out.push(c);
  return out;
};
const cell = (s: string): string => s.replace(/\|/g, '\\|');

const lines: string[] = [
  '# Lock and guide strings',
  '',
  'Generated by `npx tsx scripts/lockStrings.ts`. Every player-facing string of the lock and guide system, for review. The wording scan in `tests/mentorGuides.test.ts` checks all of them for meta terms and the names of other games.',
  '',
  `## Systems and their guides (${content.systems.all().length})`,
  '',
];
for (const sys of content.systems.all()) {
  const l = content.locks.get(sys.lock);
  lines.push(`### ${sys.name}`, '', `- Mentor: ${sys.mentor}`, `- Primer line: ${sys.summary}`, `- Lock \`${sys.lock}\` (${l.visibility}). Hint: ${l.hint}`, `- When it opens: ${l.unlockMessage}`);
  sys.steps.forEach((st, i) => lines.push(`- Step ${i + 1}: ${st.text}`));
  lines.push('');
}
const owned = new Set(content.systems.all().map((x) => x.lock));
const rest = content.locks.all().filter((l) => !owned.has(l.id));
lines.push(`## Other locks (${rest.length}: zones, dungeons, ports, crafts, classes, peoples, sub-features)`, '', '| Lock | Shows | Hint | When it opens | What it asks, in the game\'s words |', '|---|---|---|---|---|');
for (const l of rest) lines.push(`| \`${l.id}\` | ${l.visibility} | ${cell(l.hint)} | ${cell(l.unlockMessage)} | ${cell([...new Set(leaves(l.requirement).map((x) => leafText(x)))].join('; '))} |`);
writeFileSync(new URL('../docs/LOCK_STRINGS.md', import.meta.url), lines.join('\n') + '\n');
console.log(`docs/LOCK_STRINGS.md: ${content.systems.all().length} systems, ${rest.length} other locks.`);
