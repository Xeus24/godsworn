import { writeFileSync } from 'node:fs';
import { content } from '../src/data';
import { allSecrets } from '../src/engine/world/secrets';
import { SECRET_LINE_IDS } from '../src/data/story';

/** Writes docs/SECRETS.md: every secret, where it is and how to find it (spoilers). Run with `npm run secrets:md`. */
const HOW: Record<string, string> = {
  wall: 'A cracked wall: needs Detect Traps',
  gate: 'A gated find: needs an exploration skill',
  time: 'Shows only at a certain hour or moon',
  puzzle: 'Three stones: touch them west to east',
  beetle: 'A golden beetle (12 make a set)',
  fragment: 'A god’s fragment (14 make a set)',
  cache: 'A hidden cache',
  oddity: 'An oddity',
  egg: 'An easter egg',
};
const SKILL: Record<string, string> = { swimming: 'Swimming', climbing: 'Climbing', ancientScript: 'Read Ancient Script', animalSpeech: 'Animal Speech', lockpicking: 'Lockpicking', detectTraps: 'Detect Traps' };
const WHEN: Record<string, string> = { night: 'at night', blood: 'under a blood moon', moon: 'at the full moon' };

const out: string[] = ['# Godsworn: secrets (spoilers)', '', 'Generated by `npm run secrets:md`. Every secret is found once; the world screen counts them per region.', ''];
const all = allSecrets();
out.push(`**${all.length} secrets on the map, plus ${SECRET_LINE_IDS.length} secret lines said to certain heroes: ${all.length + SECRET_LINE_IDS.length} in all.**`, '');
for (const zone of content.zones.all()) {
  const list = all.filter((s) => s.zone === zone.id);
  if (!list.length) continue;
  out.push(`## ${zone.name} (${list.length})`, '', '| Secret | Where | How | Reward |', '|---|---|---|---|');
  for (const s of list) {
    const where = s.map === zone.id ? zone.name : (content.areas.find(s.map)?.name ?? content.dungeons.find(s.map)?.name ?? s.map);
    const how = [HOW[s.kind], s.gate ? `${SKILL[s.gate.skill]} ${s.gate.rank}` : '', s.when ? WHEN[s.when] : '', s.stones ? s.stones.join(' → ') : ''].filter(Boolean).join('; ');
    out.push(`| **${s.name}** | ${where} | ${how} | ${s.level * (s.kind === 'puzzle' ? 90 : 55)} gold, ${s.level * 30} XP and a gem, rune or material${s.god ? `; fragment of ${content.gods.get(s.god).name}` : ''}${s.fight ? '; a fight with yourself' : ''} |`);
  }
  out.push('');
}
out.push('## Sets', '', '- **Golden beetles (12):** one in each of the first twelve regions. Complete: 2,400 gold and the title Beetle-Keeper.', '- **God fragments (14):** one for each god, in the first fourteen regions. Complete: 4,200 gold and the title Fragment-Gatherer.', '- **Crimson Pages (7):** lore pages in the first seven regions; the Hemomancer’s secret (phase 6).', '- **Elder drakes (4), Saints’ shrines (8), the Clockwork Theatre and the Riddle Crown:** see the hidden-class and saint notes in PROGRESS.md.', '');
out.push('## Secret lines', '', `${SECRET_LINE_IDS.length} things people say only to heroes of a certain race, past, class or pairing. Talk to the people of the towns with each; each is said once, and pays 25 gold.`, '');
writeFileSync('docs/SECRETS.md', out.join('\n'));
console.log(`docs/SECRETS.md written: ${all.length} + ${SECRET_LINE_IDS.length} secrets.`);
